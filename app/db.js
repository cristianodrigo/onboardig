import pg from 'pg';
import crypto from 'node:crypto';
import bcrypt from 'bcryptjs';
import { CATALOGO, TIPOS_CONTRATO } from './catalogo.js';

export { CATALOGO, TIPOS_CONTRATO };

let pool;

function getPool() {
  const url = process.env.DATABASE_URL?.trim();
  if (!url) throw new Error('Defina DATABASE_URL.');
  if (!pool) {
    pool = new pg.Pool({ connectionString: url, max: 10 });
    pool.on('error', (err) => {
      console.error('Conexão ociosa do Postgres caiu:', err.message);
    });
  }
  return pool;
}

export async function query(sql, params = [], client = getPool()) {
  const result = await client.query(sql, params);
  return result.rows;
}

export async function withTransaction(fn) {
  const client = await getPool().connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

export async function initSchema() {
  await query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nome TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      senha_hash TEXT NOT NULL,
      papel TEXT NOT NULL CHECK (papel IN ('candidato','rh')),
      ativo BOOLEAN NOT NULL DEFAULT true,
      criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
      cpf TEXT
    );

    CREATE TABLE IF NOT EXISTS jornadas (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL UNIQUE REFERENCES users(id),
      tipo_contrato TEXT NOT NULL DEFAULT 'CLT',
      prazo_recomendado TEXT,
      criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS documentos (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      jornada_id INTEGER NOT NULL REFERENCES jornadas(id),
      tipo TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pendente'
        CHECK (status IN ('pendente','em_revisao','devolvido','aprovado')),
      arquivo_path TEXT,
      arquivo_nome TEXT,
      dados_json TEXT NOT NULL DEFAULT '{}',
      motivo_devolucao TEXT,
      enviado_em TIMESTAMPTZ,
      UNIQUE (jornada_id, tipo)
    );

    CREATE TABLE IF NOT EXISTS auditoria (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      autor_id INTEGER REFERENCES users(id),
      acao TEXT NOT NULL,
      entidade TEXT NOT NULL,
      entidade_id INTEGER NOT NULL,
      valor_antigo TEXT,
      valor_novo TEXT,
      criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE IF NOT EXISTS convites (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      token TEXT NOT NULL UNIQUE,
      user_id INTEGER NOT NULL REFERENCES users(id),
      criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
      expira_em TIMESTAMPTZ NOT NULL,
      usado_em TIMESTAMPTZ,
      revogado BOOLEAN NOT NULL DEFAULT false
    );
  `);
}

export async function auditar(autorId, acao, entidade, entidadeId, valorAntigo = null, valorNovo = null, client = getPool()) {
  await query(
    `INSERT INTO auditoria (autor_id, acao, entidade, entidade_id, valor_antigo, valor_novo)
     VALUES ($1, $2, $3, $4, $5, $6)`,
    [autorId, acao, entidade, entidadeId,
      valorAntigo == null ? null : String(valorAntigo),
      valorNovo == null ? null : String(valorNovo)],
    client
  );
}

export async function gerarConvite(userId, diasValidade = 7, client = getPool()) {
  await query(
    `UPDATE convites SET revogado = true WHERE user_id = $1 AND usado_em IS NULL`,
    [userId],
    client
  );
  const token = crypto.randomBytes(24).toString('base64url');
  await query(
    `INSERT INTO convites (token, user_id, expira_em) VALUES ($1, $2, now() + ($3 * interval '1 day'))`,
    [token, userId, diasValidade],
    client
  );
  return token;
}

export async function criarJornadaComChecklist(userId, tipoContrato = 'CLT', client = getPool()) {
  const contrato = CATALOGO[tipoContrato] ? tipoContrato : 'CLT';
  const prazo = new Date(Date.now() + 5 * 86400000).toISOString().slice(0, 10);
  const [jornada] = await query(
    `INSERT INTO jornadas (user_id, tipo_contrato, prazo_recomendado) VALUES ($1, $2, $3) RETURNING id`,
    [userId, contrato, prazo],
    client
  );
  for (const d of CATALOGO[contrato]) {
    await query(`INSERT INTO documentos (jornada_id, tipo) VALUES ($1, $2)`, [jornada.id, d.tipo], client);
  }
  return Number(jornada.id);
}

export async function seed() {
  const [{ n }] = await query(`SELECT COUNT(*)::int AS n FROM users`);
  if (n > 0) return;

  const email = process.env.SEED_RH_EMAIL?.toLowerCase().trim();
  const senha = process.env.SEED_RH_PASSWORD;
  const nome = process.env.SEED_RH_NOME?.trim() || 'RH';
  if (!email || !senha) {
    console.warn('Banco vazio: defina SEED_RH_EMAIL e SEED_RH_PASSWORD para criar o primeiro usuário RH.');
    return;
  }

  const [rh] = await query(
    `INSERT INTO users (nome, email, senha_hash, papel) VALUES ($1, $2, $3, 'rh') RETURNING id`,
    [nome, email, bcrypt.hashSync(senha, 10)]
  );
  await auditar(null, 'seed', 'user', Number(rh.id), null, 'rh inicial');
  console.log(`Seed concluído: usuário RH ${email}`);
}

export async function closePool() {
  if (pool) await pool.end();
  pool = undefined;
}
